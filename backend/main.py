app = FastAPI()
DB_FILE = "database.db"
#-----------------------------------------------|
#------------Database Setup---------------------|
#-----------------------------------------------|
def get_db_connection():
    conn = sqlite3.connect(DB_FILE)
    conn.row_factory = sqlite3.Row  # lets you access columns by name
    return conn
